import { chromium } from "playwright-core";
import { mkdir, writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";

const output = path.resolve("research/trello/local/rehearsal/browser");
await mkdir(output, { recursive: true });
const fixtures = { clients: [], users: [] };
const saveFixtures = () => writeFile(path.join(output, "fixtures.json"), JSON.stringify(fixtures, null, 2));
const stamp = Date.now();
const browser = await chromium.launch({ executablePath: process.env.E2E_CHROME ?? "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
const page = await context.newPage(), errors = [];
await page.route("**/*", (route) => new URL(route.request().url()).hostname.endsWith(".kaspersky-labs.com") ? route.abort() : route.continue());
page.on("pageerror", (error) => errors.push(error.message));
const base = "http://localhost:3100";
try {
  await page.goto(base + "/configuracoes/importar-trello/historico");
  assert.ok(page.url().includes("/login"));
  await page.locator('input[name="email"]').fill(process.env.REHEARSAL_ADMIN_EMAIL);
  await page.locator('input[name="password"]').fill(process.env.REHEARSAL_ADMIN_PASSWORD);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await page.waitForURL((url) => !url.pathname.startsWith("/login"));
  await page.goto(base + "/configuracoes/importar-trello/historico");
  await page.getByRole("heading", { name: "Histórico importado do Trello" }).waitFor();
  assert.ok((await page.locator("main").innerText()).includes("3737 cards encontrados"));
  await page.locator('select[name="mode"]').selectOption("modelos");
  await page.getByRole("button", { name: "Consultar", exact: true }).click();
  await page.getByText("69 cards encontrados", { exact: false }).waitFor();
  await page.locator("table tbody a").first().click();
  await page.getByRole("article", { name: "Detalhes importados" }).waitFor();
  await page.screenshot({ path: path.join(output, "historical-template.png") });
  await page.goto(base + "/configuracoes/importar-trello");
  const root = path.resolve("research/trello/local/api-capture/2026-10-22/boards");
  await page.getByLabel("Arquivos de quadros Trello", { exact: false }).setInputFiles([path.join(root, "69c6c052fd24c610bedb958a/board-export.json"), path.join(root, "69cc2095780821c0524d235c/board-export.json")]);
  await page.getByRole("status").filter({ hasText: "2 quadros analisados" }).waitFor();
  await page.getByText("Criar cliente", { exact: true }).click();
  await page.getByLabel("Nome do cliente a criar", { exact: true }).fill(`Ensaio cadastro cliente ${stamp}`);
  await page.getByRole("button", { name: "Criar agora e associar", exact: true }).click();
  await page.getByText("Cadastro criado e associado nesta prévia.", { exact: true }).waitFor();
  const clientId = await page.getByLabel("Cliente do quadro", { exact: true }).inputValue();
  assert.ok(clientId); fixtures.clients.push(clientId); await saveFixtures();
  await page.getByText(/^Pessoas: \d+ identidades/).click();
  const creation = page.locator("summary").filter({ hasText: /^Criar conta para esta pessoa$/ }).first().locator("..");
  await creation.locator("summary").click();
  await creation.getByLabel("Nome da pessoa a cadastrar", { exact: true }).fill(`Ensaio cadastro pessoa ${stamp}`);
  await creation.getByLabel("E-mail da nova conta", { exact: true }).fill(`ensaio.${stamp}@example.invalid`);
  await creation.getByRole("button", { name: "Criar agora e associar", exact: true }).click();
  await creation.getByText(/Senha temporária de/).waitFor();
  const userId = await creation.locator("..").locator("select").inputValue();
  assert.ok(userId); fixtures.users.push(userId); await saveFixtures();
  assert.ok((await creation.locator("code").innerText()).length >= 8);
  await creation.getByRole("button", { name: "Já guardei a senha" }).click();
  await page.getByRole("navigation", { name: "Quadros de origem" }).getByRole("button").filter({ hasText: "SPMAR - Complexo Alto" }).click();
  await page.getByLabel("Cliente do quadro", { exact: true }).selectOption(clientId);
  const downloading = page.waitForEvent("download");
  await page.getByRole("button", { name: "Exportar rascunho", exact: true }).click();
  const file = path.join(output, "destination-plan.json"); await (await downloading).saveAs(file);
  const plan = JSON.parse(await readFile(file, "utf8"));
  assert.equal(plan.boards.length, 2); assert.ok(plan.boards.every((board) => board.clientId === clientId));
  assert.notEqual(plan.boards[0].sourceBoardId, plan.boards[1].sourceBoardId);
  assert.ok(plan.boards.some((board) => Object.values(board.people).includes(userId)));
  assert.ok(!JSON.stringify(plan).includes("password"));
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false);
  const hash = createHash("sha256").update(await readFile(file)).digest("hex");
  assert.deepEqual(errors, []);
  await writeFile(path.join(output, "destination-test.json"), JSON.stringify({ passedAt: new Date().toISOString(), sharedClient: true, distinctBoards: true, accountCreation: true, passwordVisible: true, passwordExcludedFromPlan: true, planHash: hash, errors }, null, 2));
  console.log("Histórico protegido, 69 modelos consultáveis, criação de cliente/conta, cliente compartilhado por dois quadros, senha visível e ausente do plano: aprovados.");
} catch (error) { await page.screenshot({ path: path.join(output, "destination-failure.png") }); console.error(error.message); process.exitCode = 1; }
finally { await browser.close(); }
